#!/usr/bin/env node
/**
 * Renders the neighbours table: what every in-scope repository can do for the
 * others, how to call it and when (Krish, 2026-11-24: "every single repo must
 * be able to understand what other repos (capabilities) exist around it so
 * collaboration is proactive at all times").
 *
 * The one home is the `registry` in state/fleet.yaml. This writes its in-scope
 * rows to skills/krish-principles/references/capabilities.md, which every
 * session reads (the canon block names it) or fetches with Control Center
 * get_skill. The file is a checked rendering, never edited by hand:
 * `--check` fails when it differs from what the registry renders.
 *
 *   node scripts/render-capabilities.mjs          write it
 *   node scripts/render-capabilities.mjs --check  fail on drift
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { parseYaml } from './lib/yaml.mjs'

const HARNESS = resolve(fileURLToPath(import.meta.url), '../..')
export const CAPABILITIES_PATH = 'skills/krish-principles/references/capabilities.md'
export const LAYERS = ['doctrine', 'hub', 'keeper', 'specialist', 'service', 'producer', 'product']
export const SCOPES = ['in', 'personal', 'unplaced', 'dormant', 'excluded']
const LAYER_TITLE = {
  doctrine: 'Doctrine', hub: 'The hub', keeper: 'The keeper of the map', specialist: 'Specialists',
  service: 'Services', producer: 'Producers', product: 'Products',
}

const cell = (s) => String(s ?? '').replace(/\|/g, '/').replace(/\s+/g, ' ').trim()

/** The neighbours table, from the registry rows. Pure. */
export function renderCapabilities(registry) {
  const inScope = registry.filter((r) => r.scope === 'in')
  const out = [
    '# What every repository can do for you',
    '',
    '<!-- Generated by scripts/render-capabilities.mjs from the registry in state/fleet.yaml. Do not edit by hand: change the registry. -->',
    '',
    'Read this before you build or decide anything (Krish, 2026-11-24: "every single repo must be able to understand what other repos (capabilities) exist around it so collaboration is proactive at all times"). When your work matches a row\'s **When**, call that repository through its **How to call** instead of doing its job yourself. A call goes through that repository\'s own walls and widens nothing you may post, send or spend. The routes are as recorded in the registry on 2026-11-24 or later; a route that fails is a finding, so open an \`auditor-fix\` issue in your own repository naming it, and the internal auditor corrects the registry. Ventures are listed here as neighbours, not in priority order: read the order live from Control Center\'s PORTFOLIO.md.',
    '',
  ]
  for (const layer of LAYERS) {
    const rows = inScope.filter((r) => r.layer === layer)
    if (!rows.length) continue
    out.push(`## ${LAYER_TITLE[layer]}`, '', '| Repository | What it can do for you | How to call it | When |', '|---|---|---|---|')
    for (const r of rows) out.push(`| ${cell(r.name)} | ${cell(r.capability)} | ${cell(r.call)} | ${cell(r.when)} |`)
    out.push('')
  }
  const outside = registry.filter((r) => r.scope !== 'in').map((r) => r.name)
  out.push('## Outside the OS', '', `Not part of the OS, so never called for OS work: ${outside.join(', ')}.`, '')
  return out.join('\n')
}

/** Problems with the registry against the canon surfaces. Pure. Errors fail; warnings are said. */
export function registryProblems(fleet) {
  const errors = [], warnings = []
  const reg = fleet.registry || []
  if (!reg.length) return { errors: ['state/fleet.yaml has no registry'], warnings }
  const lc = (n) => String(n).toLowerCase()
  const byName = new Map()
  for (const r of reg) {
    for (const n of [r.name, ...(r.aliases || [])].map(lc)) {
      if (byName.has(n)) errors.push(`${n} is in the registry twice`)
      byName.set(n, r)
    }
    if (!SCOPES.includes(r.scope)) errors.push(`${r.name}: scope "${r.scope}" is not one of ${SCOPES.join(', ')}`)
    if (r.scope === 'in') {
      if (!LAYERS.includes(r.layer)) errors.push(`${r.name}: an in-scope repository needs a layer, one of ${LAYERS.join(', ')}`)
      for (const f of ['capability', 'call', 'when']) if (!r[f]) errors.push(`${r.name}: an in-scope repository needs ${f}, so its neighbours know how to use it`)
    }
  }
  for (const s of fleet.repos || []) {
    const r = byName.get(lc(s.name)) || (s.aliases || []).map((a) => byName.get(lc(a))).find(Boolean)
    if (!r) { errors.push(`${s.name} is a canon surface with no registry row`); continue }
    if (r.scope === 'excluded') warnings.push(`${s.name} is a canon surface but resolves to ${r.name}, which Krish excluded; retire it from the surfaces in its own change`)
    else if (r.scope === 'dormant') warnings.push(`${s.name} is a canon surface but dormant`)
  }
  return { errors, warnings }
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)
if (isMain) {
  const fleet = parseYaml(readFileSync(join(HARNESS, 'state/fleet.yaml'), 'utf8'))
  const { errors, warnings } = registryProblems(fleet)
  for (const w of warnings) console.log(`warn  ${w}`)
  if (errors.length) { for (const e of errors) console.error(`FAIL  ${e}`); process.exit(1) }
  const text = renderCapabilities(fleet.registry) + '\n'
  const abs = join(HARNESS, CAPABILITIES_PATH)
  const before = existsSync(abs) ? readFileSync(abs, 'utf8') : null
  if (process.argv.includes('--check')) {
    if (before === text) { console.log(`ok    ${CAPABILITIES_PATH}`); process.exit(0) }
    console.error(`drift ${CAPABILITIES_PATH}: run node scripts/render-capabilities.mjs`); process.exit(1)
  }
  writeFileSync(abs, text)
  console.log(`${before === text ? 'ok   ' : 'wrote'} ${CAPABILITIES_PATH}`)
}
