#!/usr/bin/env node

import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { resolve, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { parseYaml } from './lib/yaml.mjs'

const ROOT = resolve(fileURLToPath(import.meta.url), '../..')
const OUTPUT = join(ROOT, 'CURRENT.md')
const CHECK = process.argv.includes('--check')

const registry = parseYaml(readFileSync(join(ROOT, 'state/skill-registry.yaml'), 'utf8'))

const esc = (value) => String(value ?? 'unknown').replaceAll('|', '\\|')
const relative = (value) => String(value ?? '').replaceAll('\\', '/')
const release = registry.latest_approved_release
const deployments = registry.surface_deployments || {}

function readCanary(evidence) {
  if (!evidence || !String(evidence).startsWith('state/canaries/')) return null
  const path = join(ROOT, relative(evidence))
  return existsSync(path) ? JSON.parse(readFileSync(path, 'utf8')) : null
}

const localRows = []
const cloudRows = []
for (const [surface, deployment] of Object.entries(deployments)) {
  const row = {
    surface,
    release: deployment.release_id,
    parity: deployment.per_skill_hashes_exact
      ? `${deployment.per_skill_hashes_exact}/${deployment.installed_skill_count} exact`
      : 'cloud inventory only',
    status: deployment.status,
    evidence: Array.isArray(deployment.evidence) ? deployment.evidence[0] : deployment.evidence,
  }
  if (surface.endsWith('-cloud')) cloudRows.push(row)
  else localRows.push(row)
}

const canaryRows = localRows.map((row) => {
  const report = readCanary(row.evidence)
  return report ? { surface: row.surface, verdict: report.verdict, failures: report.failures || [], path: row.evidence } : null
}).filter(Boolean)

const credentialText = readFileSync(join(ROOT, 'state/credential-exposure-2026-09-12.md'), 'utf8')
const credentialStatus = (credentialText.match(/^Status:\s*(.+)$/m)?.[1]?.trim() || 'unknown').replace(/[.]+$/, '')

const lines = []
const out = (line = '') => lines.push(line)

out('<!-- Generated by scripts/render-current-state.mjs. Do not hand-edit. -->')
out('# Current harness state')
out()
out('This is the only committed human-readable statement of live harness state. It is rendered from the machine-owned evidence named below. `README.md`, architecture documents, dated reports and chat history are explanatory or historical, never current-state authorities.')
out()
out(`Rendered from registry reconciliation date **${registry.last_reconciled}**.`)
out()
out('## Release authority')
out()
out(`- Latest approved release: **${release.release_id}** (${release.tag})`)
out(`- Immutable and published: **${release.immutable === true && release.published === true ? 'yes' : 'no'}**, ${release.published_at}`)
out(`- Release source commit: \`${release.source_commit}\``)
out(`- Manifest SHA-256: \`${release.manifest_sha256}\``)
out(`- Release: ${release.release_url}`)
out(`- Current deployment verdict: **${registry.deployed_release.status}**`)
out()
out('Repository HEAD and open pull requests are volatile and must not be cached here. Read them live with `git rev-parse HEAD` and `gh pr list --state open`. Main may legitimately be newer than the latest immutable release.')
out()
out('## Surface state')
out()
out('| Surface | Release | Integrity evidence | Status |')
out('|---|---|---|---|')
for (const row of [...localRows, ...cloudRows]) out(`| ${esc(row.surface)} | ${esc(row.release)} | ${esc(row.parity)} | ${esc(row.status)} |`)
out()
out('A local hash match proves installed bytes only. It does not prove client discovery, routing or behavior. Cloud names and dates are inventory evidence, not byte parity.')
out()
out('## Behavioral evidence')
out()
if (!canaryRows.length) out('- No committed live canary reports are linked by the deployment registry.')
for (const row of canaryRows) {
  out(`- **${row.surface}: ${row.verdict}.** [Evidence](${relative(row.path)}).`)
  for (const failure of row.failures) out(`  - ${failure}`)
}
for (const row of localRows.filter((item) => item.status?.includes('manual-canary-required'))) {
  out(`- **${row.surface}: manual-required.** This client has no supported headless invocation evidence.`)
}
out()
out('## Machine clocks')
out()
out('Read `state/heartbeats.json` directly for the latest timestamps, job status and reported release. Heartbeats change independently of documentation and are deliberately not copied into this file.')
out()
out('A heartbeat status proves the scheduled job ran; it does not override deployment or behavioral evidence. A silent or old secondary-machine heartbeat means unavailable or stale, not failed. Each machine updates itself from an immutable release when it is online; the mounted drive is not a deployment channel.')
out()
out('## Other open gates')
out()
out(`- Credential exposure lifecycle: **${credentialStatus}**. See [the lifecycle record](state/credential-exposure-2026-09-12.md). Containment is not provider-side revocation.`)
out('- Claude Cloud and Perplexity remain supervised account surfaces until their personal catalogues expose trustworthy inventory, upload and rollback APIs.')
out('- GitHub repository controls are a live account-plan fact. Check them through the GitHub API; do not rely on dated setup instructions.')
out()
out('## Start the next session')
out()
out('1. Read this file, then `state/skill-registry.yaml`, `state/heartbeats.json`, and the linked failing canary reports.')
out('2. Run `git status --short`, `git rev-parse HEAD`, `git log -8 --oneline`, and `gh pr list --state open` for live repository state.')
out('3. Run `powershell.exe -NoProfile -ExecutionPolicy Bypass -File scripts/Test-Harness.ps1` before changing canon or release state.')
out('4. Treat every recorded failure as evidence. Correct the lowest owning layer and create a new release; never rewrite an immutable release or its report.')
out()
out('## Authority order')
out()
out('1. Live target readback for volatile external state.')
out('2. `state/skill-registry.yaml` for releases and deployments.')
out('3. `state/heartbeats.json` and linked machine/canary records for observed execution.')
out('4. Canonical contracts for durable policy.')
out('5. This generated rendering for human handoff.')
out('6. README, architecture and dated narrative documents for explanation and history.')
out()

const rendered = lines.join('\n')
if (CHECK) {
  const current = existsSync(OUTPUT) ? readFileSync(OUTPUT, 'utf8') : ''
  if (current !== rendered) {
    console.error('CURRENT.md is stale. Run node scripts/render-current-state.mjs and commit the result.')
    process.exit(1)
  }
  const docFailures = []
  const read = (path) => readFileSync(join(ROOT, path), 'utf8')
  if (/^## Current status$/m.test(read('README.md'))) docFailures.push('README.md duplicates generated current state.')
  if (/^Status:\s*`harness-v/m.test(read('architecture/CROSS_CLIENT_RELEASE_SYSTEM.md'))) docFailures.push('Architecture document caches a current release.')
  if (!read('AGENTS.md').includes('Read `CURRENT.md` first')) docFailures.push('AGENTS.md does not route new sessions to CURRENT.md.')
  if (!read('docs/harness/OPEN-ON-KRISH.md').includes('Historical handoff, superseded')) docFailures.push('Dated handoff is not labelled historical.')
  if (docFailures.length) {
    for (const failure of docFailures) console.error(failure)
    process.exit(1)
  }
  console.log(`CURRENT.md matches ${release.release_id} and committed surface evidence.`)
} else {
  writeFileSync(OUTPUT, rendered)
  console.log(`Rendered CURRENT.md for ${release.release_id}.`)
}
