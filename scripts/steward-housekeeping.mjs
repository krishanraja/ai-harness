#!/usr/bin/env node
/**
 * Nightly housekeeping for steward pull requests, then the digest.
 *
 * Nothing piles up and nothing waits on Krish without telling him once:
 *
 *   - An open weekly proposal document (harness/proposals-*) is closed as
 *     superseded by the change-request flow. Its observations stay in the ledger.
 *   - A change request (harness/change-*) unmerged after change_expiry_days is
 *     closed as superseded. Unmerged is a decision too, and the observer records
 *     it as revealed evidence.
 *   - A draft change request becomes ready for review only when every check has
 *     passed and the judge actually measured it (status harness/judge success).
 *   - A change request the judge could not measure for more than a day is a
 *     blocker only Krish can clear (the panel's key), and says so once.
 *
 * Then scripts/digest.mjs decides whether this week has anything to say.
 *
 *   node scripts/steward-housekeeping.mjs [--dry-run]
 *
 * Needs FLEET_TOKEN (pull request writes) and optionally CONTENT_ENGINE_KEY
 * (the Control Center board item).
 */

import { existsSync, readFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { Gh } from './lib/github.mjs'
import { loadPolicy } from './propose.mjs'
import { buildDigest, boardItem, sendBoard, writeDigest, lastSent } from './digest.mjs'

const HARNESS = resolve(fileURLToPath(import.meta.url), '../..')
const num = (v, d) => (v === undefined || v === null || v === '' ? d : Number(v))
const FOOTER = '\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_\n'
const OK_CONCLUSIONS = new Set(['success', 'skipped', 'neutral'])

/** What to do with one open steward pull request. Pure, so it is testable. */
export function decide(pr, checks, { today, expiryDays }) {
  const head = pr.head?.ref || ''
  if (head.startsWith('harness/proposals-')) return { action: 'close', reason: 'proposals-superseded' }
  if (!head.startsWith('harness/change-')) return { action: 'none' }
  const ageDays = (Date.parse(`${today}T00:00:00Z`) - Date.parse(pr.created_at)) / 86400000
  if (ageDays > expiryDays) return { action: 'close', reason: 'expired' }
  const judge = checks?.statuses?.['harness/judge']
  const runsDone = (checks?.runs || []).length > 0 && checks.runs.every((r) => r.status === 'completed')
  const runsGreen = runsDone && checks.runs.every((r) => OK_CONCLUSIONS.has(r.conclusion))
  if (judge === 'error' && ageDays > 1) return { action: 'none', blocker: 'judge-unmeasured' }
  if (pr.draft && runsGreen && judge === 'success') return { action: 'mark-ready' }
  if (!pr.draft && runsGreen && judge === 'success') return { action: 'ready' }
  return { action: 'none' }
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)
if (isMain) {
  const dryRun = process.argv.includes('--dry-run')
  const token = process.env.FLEET_TOKEN
  if (!token) { console.error('::error::FLEET_TOKEN is not set; housekeeping cannot read or close pull requests without it.'); process.exit(1) }
  const gh = new Gh(token, { dryRun })
  const policy = loadPolicy()
  const today = new Date().toISOString().slice(0, 10)
  const expiryDays = num(policy.change_expiry_days, 14)
  const ready = []
  let judgeBlocked = 0
  const log = []

  for (const pr of await gh.openPulls('ai-harness')) {
    const head = pr.head?.ref || ''
    if (!head.startsWith('harness/')) continue
    const checks = head.startsWith('harness/change-') ? await gh.checksFor('ai-harness', pr.head.sha) : null
    const d = decide(pr, checks, { today, expiryDays })
    if (d.action === 'close') {
      const body = d.reason === 'expired'
        ? `Closing unmerged after ${expiryDays} days, as superseded. Leaving it unmerged was a decision, and the observer records it. A later change request can reopen this only with materially new evidence.${FOOTER}`
        : `Superseded by the change-request flow (docs/proposals/2026-10-14-merge-ready-change-requests.md): the weekly steward now opens checked, merge-ready changes instead of proposal documents. Nothing is lost; the observations this summarised stay in the ledger and feed the next brief.${FOOTER}`
      await gh.comment('ai-harness', pr.number, body)
      await gh.addLabels('ai-harness', pr.number, ['superseded'])
      await gh.closePull('ai-harness', pr.number)
      log.push(`closed #${pr.number} (${d.reason})`)
      continue
    }
    if (d.action === 'mark-ready') { await gh.markReady(pr.node_id); log.push(`marked #${pr.number} ready`) }
    if (d.action === 'mark-ready' || d.action === 'ready') ready.push(pr)
    if (d.blocker === 'judge-unmeasured') judgeBlocked++
  }

  const blockers = judgeBlocked ? [{
    kind: 'credential', only_you: 'credential',
    title: 'Replace the judge panel key',
    detail: `${judgeBlocked} change request(s) cannot be reviewed because the judge panel's model call is refused. Replace the ANTHROPIC_API_KEY repository secret in krishanraja/ai-harness, then re-run the failed judge checks. Until then nothing is marked ready.`,
  }] : []
  const sbPath = join(HARNESS, 'state/scoreboard.jsonl')
  const scoreboard = existsSync(sbPath) ? readFileSync(sbPath, 'utf8').trim().split('\n').filter(Boolean).map((l) => JSON.parse(l)).at(-1) || null : null
  const digest = buildDigest({ ready, blockers, scoreboard, today, policy, lastSent: lastSent() })
  if (!digest) log.push('digest: nothing needs Krish this week, or it was already sent; silent.')
  else if (dryRun) log.push(`digest (dry run): ${digest.title}`)
  else {
    writeDigest(digest)
    try {
      const r = await sendBoard(boardItem(digest, { date: today }), { key: process.env.CONTENT_ENGINE_KEY, url: process.env.CONTENT_ENGINE_URL || undefined })
      log.push(r.sent ? `digest: ${digest.title}; board item written` : `digest: ${digest.title}; ${r.reason}`)
      if (!r.sent && /not set/.test(r.reason)) console.log('::warning::The digest was written but not put on the Control Center list: CONTENT_ENGINE_KEY is not set.')
    } catch (e) {
      console.log(`::error::The digest was written but the board write failed: ${String(e.message).slice(0, 200)}`)
      process.exitCode = 1
    }
  }
  console.log(log.join('\n') || 'Nothing to tidy.')
}
