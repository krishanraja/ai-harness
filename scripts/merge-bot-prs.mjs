#!/usr/bin/env node
/**
 * The harness's own pull requests merge themselves, under guards
 * (Ruling, Krish, 2026-10-28).
 *
 * Two kinds of pull request carry nothing a person needs to read: the canon
 * sync in every fleet repository, and the PC's machine evidence here. On
 * 2026-10-28 ten canon-sync pull requests had sat open for up to eleven days,
 * so fractionl-circle, full-time and mm-ctrl still carried the 10-15 and 10-17
 * canon without the North Star or taste rulings. Nothing merged them but Krish.
 *
 * A canon-sync pull request (harness/canon-sync, every fleet repository the
 * sync covers) merges when:
 *   - the fleet owner opened it from the same repository;
 *   - it changes exactly one file, the repository's canon target, and that
 *     file on its head is exactly what the current canon renders onto the
 *     current base: nothing outside the markers, nothing stale;
 *   - every check finished green, the harness's operating-context among them.
 * A machine-evidence pull request (machine-sync/<host>/<release>-<run>, here
 * only) merges when the fleet owner opened it from this repository, it changes
 * only machine records (state/deployments/, state/canaries/,
 * state/machine-runs/, brain/usage.jsonl), and every check finished green,
 * closeout among them.
 *
 * The merge names the head it checked, so a head that moved since is refused
 * by GitHub, never merged unread. Afterwards the files are read back from the
 * base branch. One pull request failing stops that pull request, never the run.
 *
 * Replaced bot pull requests close themselves: a canon sync whose base already
 * carries the current block, a machine-evidence pull request that conflicts
 * while a newer one for the same machine is open, and a docs steward fallback
 * (steward/YYYY-MM-DD) once a later steward commit landed on its base. A
 * canon-sync branch that is behind or conflicts is rebuilt on the base: it is
 * the harness's own file, so nothing a person wrote is lost. A branch someone
 * added other files to is held and reported, never rebuilt.
 *
 * Every other open pull request is listed, with its age and state, as what
 * waits on Krish (`waitingOnKrish`, read by the nightly housekeeping for the
 * digest). Nothing here merges a person's work.
 *
 *   node scripts/merge-bot-prs.mjs [--dry-run] [--repo <name>] [--wait <seconds>] [--out <file.json>]
 *
 * Needs FLEET_TOKEN: contents and pull-request write on the fleet.
 */

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { parseYaml } from './lib/yaml.mjs'
import { Gh } from './lib/github.mjs'
import { blockFor, splice, inspect } from './render.mjs'
import { canonSyncRepos } from './lib/fleet.mjs'

const HARNESS = resolve(fileURLToPath(import.meta.url), '../..')
const FOOTER = '\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_\n'
export const CANON_BRANCH = 'harness/canon-sync'
export const MACHINE_BRANCH = /^machine-sync\/([a-z0-9-]+)\/[A-Za-z0-9._-]+$/
export const STEWARD_BRANCH = /^steward\/(\d{4}-\d{2}-\d{2})(?:-[a-z0-9]+)?$/
export const MACHINE_FILES = /^(?:state\/(?:deployments|canaries|machine-runs)\/[^\s]+|brain\/usage\.jsonl)$/
const GREEN = new Set(['success', 'skipped', 'neutral'])
// This merger's own job runs as a check on the machine-evidence pull request it
// is waiting on; counting it would wait for itself forever.
export const SELF_CHECK = 'bot-pr-merge'

/** Which lifecycle a pull request belongs to. Pure. */
export function kindOf(pr, repo, owner) {
  const ref = pr.head?.ref || ''
  const own = !!pr.head?.repo?.full_name && pr.head.repo.full_name === pr.base?.repo?.full_name && pr.user?.login === owner
  if (own && ref === CANON_BRANCH) return 'canon-sync'
  if (own && repo === 'ai-harness' && MACHINE_BRANCH.test(ref)) return 'machine-evidence'
  if (own && STEWARD_BRANCH.test(ref)) return 'steward-fallback'
  // Change requests, learning reviews and the administration publisher have owners of their own.
  if (own && ref.startsWith('harness/')) return 'harness'
  return 'person'
}

/** Whether every check finished green, with the named ones among them. Pure. */
export function checksGreen(checks, required = []) {
  const runs = (checks?.runs || []).filter((r) => r.name !== SELF_CHECK)
  const statuses = Object.entries(checks?.statuses || {})
  const pending = [...runs.filter((r) => r.status !== 'completed').map((r) => r.name), ...statuses.filter(([, s]) => s === 'pending').map(([n]) => n)]
  const failing = [...runs.filter((r) => r.status === 'completed' && !GREEN.has(r.conclusion)).map((r) => r.name), ...statuses.filter(([, s]) => s === 'failure' || s === 'error').map(([n]) => n)]
  const missing = required.filter((n) => !runs.some((r) => r.name === n && r.status === 'completed' && r.conclusion === 'success'))
  return { green: !pending.length && !failing.length && !missing.length, pending, failing, missing }
}

/** What to do with an open canon-sync pull request. Pure. */
export function canonPlan({ baseText, headText, files, target, wanted, mergeable }) {
  if (wanted === baseText) return { action: 'close', reason: 'base-already-current' }
  if (files.length !== 1 || files[0] !== target) return { action: 'hold', reason: 'branch-has-other-files' }
  if (headText !== wanted || mergeable === 'dirty' || mergeable === 'behind') return { action: 'rebuild', reason: headText !== wanted ? 'stale' : mergeable }
  return { action: 'merge' }
}

/** What to do with an open machine-evidence pull request. Pure. */
export function machinePlan({ files, mergeable, newer }) {
  if (!files.length || files.some((f) => !MACHINE_FILES.test(f))) return { action: 'hold', reason: 'not-only-machine-records' }
  if (mergeable === 'dirty') return newer ? { action: 'close', reason: 'superseded-by-newer-evidence' } : { action: 'hold', reason: 'conflict' }
  if (mergeable === 'behind') return { action: 'update-branch' }
  return { action: 'merge' }
}

/** Whether a docs steward fallback was replaced by a later steward commit on its base. Pure. */
export function stewardPlan({ ref, commits }) {
  const date = ref.match(STEWARD_BRANCH)?.[1]
  const later = date && commits.find((c) => /^docs\(steward\):/.test(c.subject) && c.date > date)
  return later ? { action: 'close', reason: 'later-steward-run', by: later.sha.slice(0, 7) } : { action: 'none' }
}

const ageDays = (iso, now) => Math.max(0, Math.floor((now - Date.parse(iso)) / 86400000))

export class BotPrs {
  constructor(gh, { fleet, now = Date.now(), log = () => {} } = {}) {
    this.gh = gh
    this.fleet = fleet
    this.now = now
    this.log = log
    this.results = []
    this.waiting = []
    this.awaiting = []
  }

  record(repo, pr, kind, outcome) {
    const row = { repo, number: pr.number, kind, url: pr.html_url, ...outcome }
    this.results.push(row)
    this.log(`${repo}#${pr.number} ${kind}: ${outcome.action}${outcome.reason ? ` (${outcome.reason})` : ''}`)
    return row
  }

  async repo(entry) {
    const name = entry.name
    const pulls = await this.gh.openPulls(name)
    const base = (await this.gh.defaultBranch(name)).branch
    let stewardCommits = null
    for (const listed of pulls.sort((a, b) => String(a.created_at).localeCompare(String(b.created_at)))) {
      const kind = kindOf(listed, name, this.gh.owner)
      try {
        if (kind === 'canon-sync') await this.canon(entry, listed, base)
        else if (kind === 'machine-evidence') await this.machine(name, listed, pulls)
        else if (kind === 'steward-fallback') {
          stewardCommits ||= await this.gh.recentCommits(name, base, 50)
          const plan = stewardPlan({ ref: listed.head.ref, commits: stewardCommits })
          if (plan.action === 'close') await this.close(name, listed, kind, plan, `A later docs steward run (${plan.by}) rewrote NOW.md on ${base}, so this fallback is replaced.`)
          else await this.person(name, listed, kind)
        } else if (kind === 'person') await this.person(name, listed, kind)
      } catch (e) {
        this.record(name, listed, kind, { action: 'error', reason: String(e.status ? `github-${e.status}` : e.message).slice(0, 160) })
      }
    }
  }

  async close(repo, pr, kind, plan, why) {
    await this.gh.comment(repo, pr.number, `Closing as replaced: ${why} Bot pull requests that a newer one replaces close themselves (Ruling, Krish, 2026-10-28).${FOOTER}`)
    await this.gh.closePull(repo, pr.number)
    this.record(repo, pr, kind, plan)
  }

  async person(repo, listed, kind) {
    const pr = await this.gh.getPull(repo, listed.number)
    const checks = await this.gh.checksFor(repo, pr.head.sha)
    const state = checksGreen(checks)
    this.waiting.push({
      repo, number: pr.number, title: pr.title, url: pr.html_url, kind,
      age_days: ageDays(pr.created_at, this.now), draft: !!pr.draft,
      mergeable: pr.mergeable_state || 'unknown', failing: state.failing, pending: state.pending.length > 0,
    })
  }

  async canon(entry, listed, base) {
    const name = entry.name, target = entry.canon_target
    const pr = await this.gh.getPull(name, listed.number)
    const baseSha = await this.gh.headSha(name, base)
    const baseFile = await this.gh.getFile(name, target, baseSha)
    const baseText = baseFile ? baseFile.text : ''
    const wanted = splice(baseText, blockFor(baseText, entry))
    const found = inspect(baseText)
    if (found.present && !found.intact) return this.record(name, pr, 'canon-sync', { action: 'hold', reason: 'block-edited-in-place' })
    const headFile = await this.gh.getFile(name, target, pr.head.sha)
    const files = await this.gh.pullFiles(name, pr.number)
    const plan = canonPlan({ baseText, headText: headFile?.text ?? null, files, target, wanted, mergeable: pr.mergeable_state })
    if (plan.action === 'close') return this.close(name, pr, 'canon-sync', plan, `\`${base}\` already carries the current canon block.`)
    if (plan.action === 'hold') { this.waiting.push({ repo: name, number: pr.number, title: pr.title, url: pr.html_url, kind: 'canon-sync', age_days: ageDays(pr.created_at, this.now), draft: !!pr.draft, mergeable: pr.mergeable_state || 'unknown', failing: [], pending: false, held: plan.reason }); return this.record(name, pr, 'canon-sync', plan) }
    if (plan.action === 'rebuild') {
      await this.gh.rebuildBranch(name, CANON_BRANCH, baseSha, { [target]: wanted }, `docs(canon): sync the canon block to ${inspect(wanted).release}\n\nRendered from krishanraja/ai-harness onto ${base} at ${baseSha.slice(0, 7)}. Only the text between the\nkrish-canon markers changed; everything outside them is untouched.`)
      this.awaiting.push({ kind: 'canon-sync', entry, number: pr.number, base })
      return this.record(name, pr, 'canon-sync', plan)
    }
    return this.tryMerge(name, pr, 'canon-sync', ['operating-context'], async (merged) => {
      const after = await this.gh.getFile(name, target, merged.sha || base)
      return after?.text === wanted
    }, { entry, base })
  }

  async machine(repo, listed, pulls) {
    const pr = await this.gh.getPull(repo, listed.number)
    const host = pr.head.ref.match(MACHINE_BRANCH)[1]
    const newer = pulls.some((p) => p.number !== pr.number && MACHINE_BRANCH.test(p.head?.ref || '') && p.head.ref.match(MACHINE_BRANCH)[1] === host && String(p.created_at) > String(pr.created_at))
    const files = await this.gh.pullFiles(repo, pr.number)
    const plan = machinePlan({ files, mergeable: pr.mergeable_state, newer })
    if (plan.action === 'close') return this.close(repo, pr, 'machine-evidence', plan, `a newer evidence pull request from the same machine is open, and this one no longer merges cleanly.`)
    if (plan.action === 'hold') { this.waiting.push({ repo, number: pr.number, title: pr.title, url: pr.html_url, kind: 'machine-evidence', age_days: ageDays(pr.created_at, this.now), draft: !!pr.draft, mergeable: pr.mergeable_state || 'unknown', failing: [], pending: false, held: plan.reason }); return this.record(repo, pr, 'machine-evidence', plan) }
    if (plan.action === 'update-branch') {
      await this.gh.updateBranch(repo, pr.number, pr.head.sha)
      this.awaiting.push({ kind: 'machine-evidence', repo, number: pr.number })
      return this.record(repo, pr, 'machine-evidence', plan)
    }
    const expected = {}
    for (const f of files) expected[f] = (await this.gh.getFile(repo, f, pr.head.sha))?.text ?? null
    return this.tryMerge(repo, pr, 'machine-evidence', ['closeout'], async (merged) => {
      for (const [f, text] of Object.entries(expected)) if ((await this.gh.getFile(repo, f, merged.sha))?.text !== text) return false
      return true
    }, { repo })
  }

  /** Merge when green; leave it for the wait loop while checks run; report red. */
  async tryMerge(repo, pr, kind, required, readBack, retry) {
    const state = checksGreen(await this.gh.checksFor(repo, pr.head.sha), required)
    if (state.failing.length) {
      this.waiting.push({ repo, number: pr.number, title: pr.title, url: pr.html_url, kind, age_days: ageDays(pr.created_at, this.now), draft: !!pr.draft, mergeable: pr.mergeable_state || 'unknown', failing: state.failing, pending: false, held: 'checks-failing' })
      return this.record(repo, pr, kind, { action: 'hold', reason: `checks failing: ${state.failing.join(', ')}` })
    }
    if (!state.green) {
      this.awaiting.push({ kind, ...retry, repo, number: pr.number })
      return this.record(repo, pr, kind, { action: 'await-checks', reason: [...state.pending, ...state.missing].join(', ') || 'pending' })
    }
    const title = kind === 'canon-sync' ? `docs(canon): sync the canon block to ${inspect((await this.gh.getFile(repo, retry.entry.canon_target, pr.head.sha))?.text || '').release} (#${pr.number})` : `${pr.title} (#${pr.number})`
    const merged = await this.gh.mergePull(repo, pr.number, { sha: pr.head.sha, title, message: kind === 'canon-sync' ? 'Only the text between the krish-canon markers changed. Merged by scripts/merge-bot-prs.mjs.' : 'Closeout: not needed, machine evidence. Merged by scripts/merge-bot-prs.mjs.' })
    if (merged?.merged !== true) return this.record(repo, pr, kind, { action: 'error', reason: 'merge-not-confirmed' })
    if (!merged.dryRun && !(await readBack(merged))) return this.record(repo, pr, kind, { action: 'error', reason: 'readback-mismatch', merge: merged.sha })
    return this.record(repo, pr, kind, { action: 'merged', merge: merged.sha || null })
  }

  /** Re-check what was waiting on checks until it merges or time runs out. */
  async drain(seconds, { sleep = (ms) => new Promise((r) => setTimeout(r, ms)), every = 20 } = {}) {
    const deadline = Date.now() + seconds * 1000
    while (this.awaiting.length && Date.now() < deadline) {
      await sleep(every * 1000)
      const batch = this.awaiting.splice(0)
      for (const item of batch) {
        const repo = item.entry ? item.entry.name : item.repo
        try {
          const listed = await this.gh.getPull(repo, item.number)
          if (listed.state !== 'open') continue
          // Drop this pull request's earlier rows: the latest outcome is the one that counts.
          this.results = this.results.filter((r) => !(r.repo === repo && r.number === item.number))
          this.waiting = this.waiting.filter((r) => !(r.repo === repo && r.number === item.number))
          if (item.kind === 'canon-sync') await this.canon(item.entry, listed, item.base)
          else await this.machine(repo, listed, await this.gh.openPulls(repo))
        } catch (e) {
          this.record(repo, { number: item.number }, item.kind, { action: 'error', reason: String(e.status ? `github-${e.status}` : e.message).slice(0, 160) })
        }
      }
    }
  }

  report() {
    return { schema_version: 1, generated_at: new Date(this.now).toISOString(), results: this.results, waiting: this.waiting.sort((a, b) => b.age_days - a.age_days) }
  }
}

/** The repositories this runs over: every repository the canon sync covers. */
export function targets(fleet, only = null) {
  return canonSyncRepos(fleet).filter((r) => !only || r.name.toLowerCase() === String(only).toLowerCase())
}

/** Open pull requests that only Krish can move, across the fleet, for the digest. Read-only. */
export async function waitingOnKrish(gh, fleet, { now = Date.now(), minAgeDays = 1 } = {}) {
  const run = new BotPrs(gh, { fleet, now })
  for (const entry of targets(fleet)) {
    try {
      for (const listed of await gh.openPulls(entry.name)) {
        const kind = kindOf(listed, entry.name, gh.owner)
        if (kind === 'person' && !listed.draft && ageDays(listed.created_at, now) >= minAgeDays) await run.person(entry.name, listed, kind)
      }
    } catch { /* one unreadable repository never hides the rest */ }
  }
  return run.waiting.sort((a, b) => b.age_days - a.age_days)
}

/** The digest line for what waits on Krish, or null. Pure. */
export function waitingBlocker(waiting, { max = 8 } = {}) {
  if (!waiting.length) return null
  const state = (w) => w.mergeable === 'dirty' ? 'conflicts' : w.failing.length ? `red: ${w.failing.slice(0, 2).join(', ')}` : w.held ? `held: ${w.held}` : 'ready'
  const shown = waiting.slice(0, max).map((w) => `${w.repo}#${w.number} ${w.title} (${w.age_days} days, ${state(w)})`)
  return {
    kind: 'review', only_you: 'permission',
    title: waiting.length === 1 ? '1 pull request waits on you' : `${waiting.length} pull requests wait on you`,
    detail: `${shown.join('; ')}${waiting.length > max ? `; and ${waiting.length - max} more` : ''}. Merge, close or tell a session what to change; the harness's own pull requests merge themselves.`,
  }
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)
if (isMain) {
  const args = process.argv.slice(2), flag = (f) => { const i = args.indexOf(f); return i < 0 ? null : args[i + 1] }
  const token = process.env.FLEET_TOKEN
  if (!token) { console.error('::error::FLEET_TOKEN is not set; bot pull requests cannot be read or merged without it.'); process.exit(1) }
  const fleet = parseYaml(readFileSync(join(HARNESS, 'state/fleet.yaml'), 'utf8'))
  const gh = new Gh(token, { owner: fleet.owner, dryRun: args.includes('--dry-run') })
  const run = new BotPrs(gh, { fleet, log: (l) => console.log(l) })
  for (const entry of targets(fleet, flag('--repo'))) {
    try { await run.repo(entry) } catch (e) { console.log(`::warning::${entry.name}: ${String(e.status ? `github-${e.status}` : e.message).slice(0, 160)}`) }
  }
  await run.drain(Number(flag('--wait') || 0))
  const report = run.report()
  if (flag('--out')) { mkdirSync(dirname(resolve(flag('--out'))), { recursive: true }); writeFileSync(flag('--out'), JSON.stringify(report, null, 2) + '\n') }
  const merged = report.results.filter((r) => r.action === 'merged').length, closed = report.results.filter((r) => r.action === 'close').length
  const errors = report.results.filter((r) => r.action === 'error')
  console.log(`\n${merged} merged, ${closed} closed as replaced, ${run.awaiting.length} still waiting on checks, ${report.waiting.length} waiting on Krish.`)
  for (const e of errors) console.log(`::warning::${e.repo}#${e.number} ${e.kind}: ${e.reason}`)
}
