#!/usr/bin/env node
/**
 * Open each guarded change package as a draft change-request pull request.
 *
 * This is the deterministic half after the model. The model drafted packages
 * under changes/ with no write credential; this step, which holds the fleet
 * token, does everything that touches git or GitHub, and only for packages
 * scripts/change-guard.mjs passes:
 *
 *   1. branch harness/change-<date>-<type>-<slug> from origin/main
 *   2. copy the package's files in
 *   3. render docs/proposals/<date>-<slug>.md from change.json (the provenance)
 *   4. record provenance: brain-rules --revise --kind proposal --ref <that file>
 *   5. run the validators; a failure skips the package, it never half-opens one
 *   6. commit with a `Harness-Steward: change-request` trailer, so the judge
 *      never accepts a ruling from it
 *   7. push, and open a DRAFT pull request. scripts/steward-housekeeping.mjs
 *      marks it ready once its checks pass and the judge has measured it.
 *
 * Merging is acceptance. Nothing here merges, releases or installs anything.
 *
 *   node scripts/open-changes.mjs [--dir changes] [--max <n>] [--dry-run | --local]
 *
 * --dry-run guards and renders only. --local does everything up to and
 * including the commit on a local branch, and pushes and opens nothing: it is
 * how the opener is exercised in a scratch clone.
 */

import { execFileSync } from 'node:child_process'
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { checkPackage } from './change-guard.mjs'
import { loadPolicy } from './propose.mjs'
import { Gh } from './lib/github.mjs'

const HARNESS = resolve(fileURLToPath(import.meta.url), '../..')
const num = (v, d) => (v === undefined || v === null || v === '' ? d : Number(v))

export function branchName(change, date) {
  return `harness/change-${date}-${change.type}-${change.slug}`
}

const addDays = (date, n) => new Date(Date.parse(`${date}T00:00:00Z`) + n * 86400000).toISOString().slice(0, 10)
const bullets = (v) => (Array.isArray(v) ? v : [v]).map((x) => `- ${x}`).join('\n')

/** The proposal document a change request carries: its provenance in brain/rules.yaml. */
export function renderProposal(change, guard, { date }) {
  const files = guard.files.map((f) => `- \`${f.path}\` (${f.kind}, +${f.added} -${f.removed})`).join('\n')
  return [
    `# ${change.title}`,
    '',
    `Status: change request, awaiting Krish. Opened by the weekly harness steward on ${date} for candidate \`${change.candidate_id}\` (${change.type}). Merging this pull request is the acceptance; it does not release anything.`,
    '',
    '## Evidence',
    '',
    change.why,
    '',
    `Ledger ids: ${change.evidence_ids.map((id) => `\`${id}\``).join(', ')}.`,
    '',
    '## Alternative explanations',
    '',
    change.alternative_explanations,
    '',
    '## What changes',
    '',
    files,
    '',
    `Always-on context: ${guard.delta > 0 ? '+' : ''}${guard.delta} characters.${change.growth_justified ? ` Growth justified: ${change.growth_justified}` : ''}`,
    '',
    '## If wrong',
    '',
    change.if_wrong,
    '',
    '## Validation',
    '',
    change.validation,
    '',
    '## Prior known-good and rollback',
    '',
    change.rollback,
    '',
  ].join('\n')
}

export function renderBody(change, guard, { date, expiryDays, proposalPath }) {
  return [
    `**${change.title}**`,
    '',
    `Merging is acceptance; it does not release. Unmerged, this closes itself on ${addDays(date, expiryDays)}.`,
    '',
    bullets([
      `Candidate: \`${change.candidate_id}\` (${change.type})`,
      `Files: ${guard.files.map((f) => `\`${f.path}\``).join(', ')}`,
      `Always-on context: ${guard.delta > 0 ? '+' : ''}${guard.delta} characters`,
      `Eval cases added: ${guard.evalLines}`,
      `Evidence, alternatives, rollback: \`${proposalPath}\``,
    ]),
    '',
    change.why,
    '',
    '---',
    '_Generated by [Claude Code](https://claude.ai/code)_',
    '',
  ].join('\n')
}

function sh(cmd, args, opts = {}) {
  // stdin must be a pipe when there is input (the commit message), or git reads nothing.
  return execFileSync(cmd, args, { cwd: HARNESS, encoding: 'utf8', stdio: [opts.input === undefined ? 'ignore' : 'pipe', 'pipe', 'pipe'], ...opts })
}

export function packages(dir) {
  if (!existsSync(dir)) return []
  // The process review's package first: it was given its slot before the model drafted.
  return readdirSync(dir).filter((n) => existsSync(join(dir, n, 'change.json')))
    .sort((a, b) => Number(b.startsWith('process-')) - Number(a.startsWith('process-')) || a.localeCompare(b))
    .map((n) => join(dir, n))
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)
if (isMain) {
  const args = process.argv.slice(2)
  const flag = (f) => { const i = args.indexOf(f); return i === -1 ? null : args[i + 1] }
  const dryRun = args.includes('--dry-run')
  const local = args.includes('--local')
  const dir = resolve(flag('--dir') || join(HARNESS, 'changes'))
  const policy = loadPolicy()
  const max = num(flag('--max'), num(policy.decision_budget, 3))
  const date = new Date().toISOString().slice(0, 10)
  const expiryDays = num(policy.change_expiry_days, 14)
  const token = process.env.FLEET_TOKEN
  if (!dryRun && !local && !token) { console.error('::error::FLEET_TOKEN is not set; a change request cannot be pushed or opened without it.'); process.exit(1) }
  const gh = dryRun || local ? null : new Gh(token)
  const summary = []
  let opened = 0
  for (const pkg of packages(dir)) {
    const guard = checkPackage(pkg)
    const change = guard.change || {}
    if (!guard.ok) {
      summary.push(`refused ${pkg}: ${guard.problems.join('; ')}`)
      console.log(`::warning::change package ${pkg} refused by the guard: ${guard.problems.join('; ')}`)
      continue
    }
    if (opened >= max) { summary.push(`skipped ${change.slug}: the decision budget (${max}) is used`); continue }
    const branch = branchName(change, date)
    const proposalPath = `docs/proposals/${date}-${change.slug}.md`
    if (dryRun) {
      console.log(`--- would open ${branch}\n${renderProposal(change, guard, { date })}`)
      opened++
      continue
    }
    try {
      sh('git', ['fetch', '--quiet', 'origin', 'main'])
      if (!local && sh('git', ['ls-remote', '--heads', 'origin', branch]).trim()) { summary.push(`skipped ${branch}: already exists`); continue }
      sh('git', ['checkout', '--quiet', '-B', branch, 'origin/main'])
      for (const f of guard.files) { mkdirSync(dirname(join(HARNESS, f.path)), { recursive: true }); cpSync(join(pkg, 'files', f.path), join(HARNESS, f.path)) }
      writeFileSync(join(HARNESS, proposalPath), renderProposal(change, guard, { date }))
      const supersedes = Object.entries(change.supersedes || {}).map(([a, b]) => `${a}=${b}`).join(',')
      sh(process.execPath, ['scripts/brain-rules.mjs', '--revise', '--kind', 'proposal', '--ref', proposalPath, ...(supersedes ? ['--supersedes', supersedes] : [])])
      for (const check of [['scripts/brain-rules.mjs', '--check'], ['scripts/render.mjs', '--check'], ['scripts/validate-surfaces.mjs'], ['scripts/test-observe.mjs'], ['scripts/test-propose.mjs']]) {
        sh(process.execPath, check)
      }
      sh('git', ['add', '--', ...guard.files.map((f) => f.path), proposalPath, 'brain/rules.yaml'])
      sh('git', ['-c', 'user.name=Claude', '-c', 'user.email=noreply@anthropic.com', 'commit', '--quiet', '-F', '-'], {
        input: `${change.title}\n\n${change.why}\n\nCandidate ${change.candidate_id}; evidence ${change.evidence_ids.join(', ')}.\nAlways-on context ${guard.delta > 0 ? '+' : ''}${guard.delta} characters.${change.growth_justified ? `\nGrowth justified: ${change.growth_justified}` : ''}\n\nHarness-Steward: change-request\n`,
      })
      if (local) { summary.push(`committed ${branch} locally (not pushed)`); opened++; continue }
      const remote = `https://x-access-token:${token}@github.com/${gh.owner}/ai-harness.git`
      sh('git', ['push', '--quiet', remote, `HEAD:refs/heads/${branch}`])
      const pr = await gh.openPull('ai-harness', {
        title: `Change request: ${change.title}`.slice(0, 120), head: branch, base: 'main', draft: true,
        body: renderBody(change, guard, { date, expiryDays, proposalPath }),
      })
      summary.push(`opened #${pr.number} ${branch}`)
      opened++
    } catch (e) {
      const msg = String(e.stderr || e.message).split(token || '\u0000').join('[token]').slice(0, 400)
      summary.push(`failed ${change.slug}: ${msg}`)
      console.log(`::warning::change ${change.slug} was not opened: ${msg}`)
    } finally {
      if (!local) { try { sh('git', ['checkout', '--quiet', '--force', 'origin/main']) } catch { /* best effort */ } }
    }
  }
  console.log(summary.length ? summary.join('\n') : 'No change packages. Nothing opened, which is a normal week.')
  if (process.env.GITHUB_STEP_SUMMARY) writeFileSync(process.env.GITHUB_STEP_SUMMARY, `### Change requests\n\n${summary.map((s) => `- ${s}`).join('\n') || '- none this week'}\n`, { flag: 'a' })
}
